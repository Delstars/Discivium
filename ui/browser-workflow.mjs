import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdir, readFile } from 'node:fs/promises';
await mkdir('browser-evidence',{recursive:true});
const browser=await chromium.launch({headless:true});
const base='http://127.0.0.1:8000/ui/';
const errors=[];
async function login(user){
 const ctx=await browser.newContext({viewport:{width:1440,height:1000},acceptDownloads:true});
 const page=await ctx.newPage();
 page.on('pageerror',e=>errors.push(String(e)));
 await page.goto(base);
 await page.locator('#login-username').fill(user);
 await page.locator('#login-password').fill('DemoOnly!2026');
 await page.getByRole('button',{name:'Sign In',exact:true}).click();
 await page.getByRole('navigation',{name:'Primary navigation'}).waitFor();
 return {ctx,page};
}
async function snapshot(page){return page.evaluate(async()=>{const res=await fetch('/api/state');if(!res.ok)throw Error('state '+res.status);return res.json()});}
async function navigate(page,hash){await page.goto(base+'#/'+hash);}
async function perform(page,action,trigger){
 const response=page.waitForResponse(r=>r.url().endsWith('/api/actions/'+action)&&r.request().method()==='POST');
 const refresh=page.waitForResponse(r=>r.url().endsWith('/api/state')&&r.ok());
 await trigger();const r=await response;assert.equal(r.status(),200,action);
 await refresh;
}
const pdf=Buffer.from('%PDF-1.4\n1 0 obj\n<< /Type /Catalog /Pages 2 0 R >>\nendobj\n2 0 obj\n<< /Type /Pages /Kids [] /Count 0 >>\nendobj\ntrailer\n<< /Root 1 0 R >>\n%%EOF\n');
try{
 const lecturer=await login('lecturer'),student=await login('student'),advisor=await login('advisor'),admin=await login('admin');
 const l=lecturer.page,s=student.page,a=advisor.page,g=admin.page;
 await navigate(l,'course/1');
 await l.getByRole('button',{name:'Publish Assignment',exact:true}).first().click();
 let dialog=l.getByRole('dialog');
 await dialog.locator('#pub-title').fill('Browser verified architecture task');
 await dialog.locator('#pub-desc').fill('Submit the fictional test document.');
 await dialog.locator('#pub-due').fill('2099-01-01T12:00');
 await dialog.locator('#pub-max').fill('30');
 await perform(l,'publish',()=>dialog.getByRole('button',{name:'Publish Assignment',exact:true}).click());
 await dialog.waitFor({state:'hidden'});
 console.log('Lecturer published assignment from real UI');
 await s.reload();
 await navigate(s,'assignments');
 await s.getByRole('button',{name:'Submit PDF / DOCX',exact:true}).first().click();
 dialog=s.getByRole('dialog');
 await dialog.locator('#asg-upload-file').setInputFiles({name:'browser-proof.pdf',mimeType:'application/pdf',buffer:pdf});
 await perform(s,'submit',()=>dialog.getByRole('button',{name:'Submit File',exact:true}).click());
 await dialog.waitFor({state:'hidden'});
 let studentState=await snapshot(s);
 let assignment=studentState.courses.find(c=>c.id===1).assignments.find(a=>a.title==='Browser verified architecture task');
 assert.equal(assignment.submissions[0].status,'submitted');
 console.log('Student uploaded real bytes from UI');
 await l.reload();await navigate(l,'course/1');
 await l.getByRole('button',{name:'Grade',exact:true}).first().waitFor();
 const dl=l.waitForEvent('download');
 await l.getByRole('button',{name:'File',exact:true}).first().click();
 const download=await dl; assert.deepEqual(await readFile(await download.path()),pdf);
 await l.getByRole('button',{name:'Grade',exact:true}).first().click();
 dialog=l.getByRole('dialog');
 await dialog.locator('#grade-score').fill('27');
 await dialog.locator('#grade-comment').fill('Verified feedback from lecturer.');
 await perform(l,'grade',()=>dialog.getByRole('button',{name:'Release Grade & Feedback',exact:true}).click());
 await dialog.waitFor({state:'hidden'});
 await l.getByRole('button',{name:'Release Final Result',exact:true}).first().click();
 dialog=l.getByRole('dialog');
 await perform(l,'release-result',()=>dialog.getByRole('button',{name:'Release Final Result',exact:true}).click());
 await dialog.waitFor({state:'hidden'});
 await s.reload();await navigate(s,'assignments');
 await s.getByText('Verified feedback from lecturer.',{exact:true}).waitFor();
 studentState=await snapshot(s);
 assert.equal(studentState.record.results.find(r=>r.course_id===1).percentage,90);
 console.log('Lecturer downloaded, graded and released result; student saw feedback and record');
 await navigate(s,'registration');
 const alg=s.getByRole('row').filter({hasText:'BCS310'}).filter({hasText:'Algorithms I'}).first();
 await perform(s,'register',()=>alg.getByRole('button',{name:'Register',exact:true}).click());
 await alg.getByText('Enrolled',{exact:true}).waitFor();
 console.log('Student registered through UI');
 await navigate(s,'finance');
 await s.getByRole('button',{name:'Simulate Pay',exact:true}).first().click();
 await perform(s,'pay',()=>s.getByRole('dialog').getByRole('button',{name:'Confirm Simulated Payment',exact:true}).click());
 assert.equal((await snapshot(s)).finance[0].status,'paid');
 console.log('Student settled simulated invoice through UI');
 await navigate(s,'advising');
 await s.getByRole('button',{name:'Grant Consent',exact:true}).first().click();
 await perform(s,'consent',()=>s.getByRole('dialog').getByRole('button',{name:'Grant Access',exact:true}).click());
 await a.reload();
 await a.locator('#advisor-note-input').waitFor();
 await a.locator('#advisor-note-input').fill('Browser-verified advising note.');
 await perform(a,'advising-note',()=>a.getByRole('button',{name:'Save Shared Note',exact:true}).click());
 await s.reload();await navigate(s,'advising');
 await s.getByText('Browser-verified advising note.',{exact:true}).waitFor();
 await s.getByRole('button',{name:'Revoke Consent',exact:true}).first().click();
 await perform(s,'consent',()=>s.getByRole('dialog').getByRole('button',{name:'Revoke Access',exact:true}).click());
 await a.reload();
 await a.getByText('Academic and attendance records are withheld',{exact:true}).waitFor();
 const advisee=(await snapshot(a)).advisees.find(x=>x.id===2);
 assert.equal(advisee.consent,0);assert.equal('record' in advisee,false);
 console.log('Consent granted, advising note shared, consent revoked and private record withheld');
 await g.reload();await navigate(g,'audit');
 let aud=(await snapshot(g)).governance.audit;
 for(const name of ['published','submitted','graded','result_released','registered','simulated_payment','consent_changed','advising_note'])assert.ok(aud.some(x=>x.action===name),name);
 await g.screenshot({path:'browser-evidence/admin-audit-workflow.png',fullPage:true});
 await s.screenshot({path:'browser-evidence/student-advising-workflow.png',fullPage:true});
 assert.deepEqual(errors,[]);
 console.log('Audit evidence verified; all live browser workflows passed');
}finally{await browser.close();}
